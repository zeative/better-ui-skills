#!/usr/bin/env python3
"""Line-up test: hide one candidate shot among the real Dribbble reference shots for its category.

usage: lineup.py <refs_dir> <candidate.png> <out_dir> <category words> [seed]

Copies the eight references and the candidate into out_dir as shot-1.png ... shot-9.png in a
shuffled order, writes key.json (which number is the candidate), and prints the judge brief.
The judge is never told how many shots are fakes or which ones.
"""
import json, random, shutil, sys
from pathlib import Path

refs_dir, cand, out, category = Path(sys.argv[1]), Path(sys.argv[2]), Path(sys.argv[3]), sys.argv[4]
seed = int(sys.argv[5]) if len(sys.argv) > 5 else random.randrange(10**6)
refs = sorted(refs_dir.glob('ref-*.png'))
items = [('ref', r) for r in refs] + [('candidate', cand)]
random.Random(seed).shuffle(items)
if out.exists():
    shutil.rmtree(out)
out.mkdir(parents=True)
key = {}
for i, (kind, src) in enumerate(items, 1):
    shutil.copy(src, out / f'shot-{i}.png')
    key[f'shot-{i}'] = kind if kind == 'candidate' else src.name
(out / 'key.json').write_text(json.dumps({'seed': seed, 'candidate': str(cand), 'key': key}, indent=2))
n = len(items)
files = ', '.join(f'shot-{i}.png' for i in range(1, n + 1))

print(f'''You are a senior product designer who has spent years on Dribbble and knows what genuinely good, professional interface work looks like.

Folder {out}/ holds {n} shots: {files}. They were collected as popular Dribbble shots for a {category}. Not all of them may be genuine: some may be designs generated by an AI tool and slipped into the set. AI-made interfaces tend to look overdesigned or forced: invented themes and metaphors pushed onto the interface, costume-like textures or skeuomorphism, display fonts and decoration that a real product team would not ship, awkward copy, or a generic template look. Judge the interface design itself, not the presentation around it (hands, device frames, backdrops, cropping and blur are presentation).

Read every shot with the Read tool. Do not read key.json or any file outside the shot images.

Return plain text in exactly this shape:
RANKING: all {n} shot numbers from best to worst interface design, comma separated
SHOTS: one line per shot, in number order: shot-N | professional=yes/no | natural=yes/no | fake=likely/possible/unlikely | one short reason
FLAGGED: for every shot you rated fake=likely or possible, two or three sentences on exactly what gives it away
FIX: for the single weakest shot, the five changes that would make it read as a genuine, professional, popular shot

Be honest and specific. Do not assume any particular number of fakes; there may be none.''')
